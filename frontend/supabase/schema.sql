-- Produk
create table if not exists public.products (
  id bigint generated by default as identity primary key,
  name text not null,
  price bigint not null default 0 check (price >= 0),
  stock integer not null default 0 check (stock >= 0),
  created_at timestamptz not null default now()
);
alter table public.products add column if not exists category text not null default 'Umum';

-- Pengaturan (1 baris)
create table public.settings (
  id bigint primary key default 1 check (id = 1),
  store_name text default 'BAPI FARMA',
  store_owner text default '',
  store_address text default '',
  store_phone text default '',
  store_email text default '',
  cashier_name text default 'Kasir',
  store_logo text default '',
  discount_enabled boolean not null default false,
  discount_percentage numeric not null default 0,
  minimum_discount_amount bigint not null default 0,
  receipt_footer text default 'Terima kasih',
  receipt_note text default '',
  show_logo boolean not null default true,
  show_address boolean not null default true,
  show_phone boolean not null default true,
  show_cashier boolean not null default true,
  show_date boolean not null default true,
  show_time boolean not null default true,
  primary_color text default '#168b72',
  dark_mode boolean not null default false
);
insert into public.settings (id) values (1);

-- Transaksi
create table public.transactions (
  id bigint generated by default as identity primary key,
  invoice_no text unique,
  cashier text,
  payment_method text not null default 'Tunai',
  subtotal bigint not null,
  discount bigint not null default 0,
  total bigint not null,
  amount_paid bigint not null,
  change_amount bigint not null default 0,
  created_at timestamptz not null default now()
);

create table public.transaction_items (
  id bigint generated by default as identity primary key,
  transaction_id bigint not null references public.transactions(id) on delete cascade,
  product_id bigint references public.products(id) on delete set null,
  product_name text not null,
  price bigint not null,
  qty integer not null check (qty > 0),
  subtotal bigint not null
);
create index if not exists transaction_items_trx_idx on public.transaction_items(transaction_id);

-- Fungsi bayar (atomik: stok kepotong + transaksi tercatat sekaligus)
create or replace function public.create_transaction(
  p_items jsonb,
  p_payment_method text,
  p_amount_paid bigint
) returns jsonb
language plpgsql
as $$
declare
  v_item jsonb;
  v_product public.products%rowtype;
  v_settings public.settings%rowtype;
  v_qty integer;
  v_subtotal bigint := 0;
  v_discount bigint := 0;
  v_total bigint;
  v_trx_id bigint;
  v_invoice text;
begin
  if p_items is null or jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then
    raise exception 'Keranjang kosong';
  end if;

  select * into v_settings from public.settings where id = 1;

  for v_item in select * from jsonb_array_elements(p_items) loop
    v_qty := (v_item->>'qty')::int;
    if v_qty is null or v_qty <= 0 then
      raise exception 'Jumlah tidak valid';
    end if;
    select * into v_product from public.products
      where id = (v_item->>'product_id')::bigint for update;
    if not found then
      raise exception 'Produk tidak ditemukan';
    end if;
    if v_product.stock < v_qty then
      raise exception 'Stok % tidak cukup (sisa %)', v_product.name, v_product.stock;
    end if;
    v_subtotal := v_subtotal + v_product.price * v_qty;
  end loop;

  if v_settings.discount_enabled and v_subtotal >= v_settings.minimum_discount_amount then
    v_discount := round(v_subtotal * v_settings.discount_percentage / 100);
  end if;
  v_total := v_subtotal - v_discount;

  if p_amount_paid < v_total then
    raise exception 'Uang pembayaran kurang';
  end if;

  insert into public.transactions
    (cashier, payment_method, subtotal, discount, total, amount_paid, change_amount)
  values
    (v_settings.cashier_name, coalesce(p_payment_method, 'Tunai'), v_subtotal,
     v_discount, v_total, p_amount_paid, p_amount_paid - v_total)
  returning id into v_trx_id;

  v_invoice := 'TRX-' || to_char(now() at time zone 'Asia/Jakarta', 'YYYYMMDD')
               || '-' || lpad(v_trx_id::text, 4, '0');
  update public.transactions set invoice_no = v_invoice where id = v_trx_id;

  for v_item in select * from jsonb_array_elements(p_items) loop
    v_qty := (v_item->>'qty')::int;
    select * into v_product from public.products
      where id = (v_item->>'product_id')::bigint;
    insert into public.transaction_items
      (transaction_id, product_id, product_name, price, qty, subtotal)
    values
      (v_trx_id, v_product.id, v_product.name, v_product.price, v_qty, v_product.price * v_qty);
    update public.products set stock = stock - v_qty where id = v_product.id;
  end loop;

  return jsonb_build_object(
    'id', v_trx_id, 'invoice_no', v_invoice, 'subtotal', v_subtotal,
    'discount', v_discount, 'total', v_total,
    'amount_paid', p_amount_paid, 'change', p_amount_paid - v_total
  );
end;
$$;

revoke execute on function public.create_transaction(jsonb, text, bigint) from public, anon;
grant execute on function public.create_transaction(jsonb, text, bigint) to authenticated;

